#include <iostream>

using namespace std;

int main() {

int x;
int y;
cout << "choose a number" << endl;
cin >> x;
cout << "now choose another number" << endl;
cin >> y;
cout << "your results are in!" << endl;
cout << x << " + " << y << " = " << x+y << endl;
cout << x << " - " << y << " = " << x-y << endl;
cout << x << " * " << y << " = " << x*y << endl;
cout << x << " / " << y << " = " << x/y << endl;
return 0;

}
